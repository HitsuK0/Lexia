-- ────────────────────────────────────────────────────────────
-- Delete an Interpreter
-- Dependencies: Absence, Coordinator, RDVInterpreter,
--               AcademicSkillInterpreter, ProfessionalSkillInterpreter,
--               Beneficiary.FKnumInterpreter
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION trg_delete_interpreter_fn() RETURNS TRIGGER AS $$
BEGIN
    DELETE FROM Absence                  WHERE FKnumInterpreter = OLD.numInterpreter;

    DELETE FROM Coordinator              WHERE FKnumInterpreter = OLD.numInterpreter;

    DELETE FROM RDVInterpreter           WHERE numInterpreter   = OLD.numInterpreter;

    DELETE FROM AcademicSkillInterpreter     WHERE numInterpreter = OLD.numInterpreter;

    DELETE FROM ProfessionalSkillInterpreter WHERE numInterpreter = OLD.numInterpreter;

    UPDATE Beneficiary SET FKnumInterpreter = NULL WHERE FKnumInterpreter = OLD.numInterpreter;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_delete_interpreter
BEFORE DELETE ON Interpreter
FOR EACH ROW
EXECUTE FUNCTION trg_delete_interpreter_fn();


