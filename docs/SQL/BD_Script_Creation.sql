                            FKTimeSlotPunctual INTEGER,
                            CONSTRAINT FKTimeSlotPunctualAppointment FOREIGN KEY(FKTimeSlotPunctual) REFERENCES TimeSlotPunctual (numTimeSlot));

CREATE TABLE RequiredAcademicSkill (    numAppointment INTEGER,
                                        numAcademicSkill INTEGER,
                                        CONSTRAINT PKRequiredAcademicSkill PRIMARY KEY (numAppointment, numAcademicSkill),
                                        CONSTRAINT FKnumAppointmentRequiredAcademicSkill FOREIGN KEY(numAppointment) REFERENCES Appointment (numAppointment),
                                        CONSTRAINT FKnumAcademicSkillRequired FOREIGN KEY(numAcademicSkill) REFERENCES AcademicSkill (numAcademicSkill));

CREATE TABLE ProfessionalSkill( numProfessionalSkill INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                designation VARCHAR(255));

