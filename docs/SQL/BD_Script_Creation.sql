-- pgcrypto is only used by BD_Script_Insertion.sql to seed bcrypt-hashed
-- passwords (crypt(...,'bf')) compatible with the Java BCrypt check.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE Address (  numAddress INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        postalCode INTEGER NOT NULL,
                        postalBox VARCHAR(255) NOT NULL,
                        locality VARCHAR(255) NOT NULL,
                        hamlet VARCHAR(255));

CREATE TABLE TimeSlotBase ( numTimeSlot INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            startTime TIMESTAMP NOT NULL,
                            duration TIMESTAMP NOT NULL,
                            dayNumber INTEGER NOT NULL);

CREATE TABLE TimeSlotPunctual ( numTimeSlot INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                startTime TIMESTAMP NOT NULL,
                                duration TIMESTAMP NOT NULL,
                                startDate DATE NOT NULL,
                                endDate DATE NOT NULL);

CREATE TABLE Interpreter (  numInterpreter INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            login VARCHAR(255) NOT NULL,
                            password VARCHAR(255) NOT NULL,
                            lastName VARCHAR(255) NOT NULL,
                            firstName VARCHAR(255) NOT NULL,
                            emailAddress VARCHAR(255) NOT NULL,
                            phoneNumber VARCHAR(255) NOT NULL,
                            weeklyWorkHours INTEGER NOT NULL,
                            FKAddress INTEGER NOT NULL,
                            CONSTRAINT FKAddressInterpreter FOREIGN KEY(FKAddress) REFERENCES Address (numAddress));

CREATE TABLE Absence (  numAbsence INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        status VARCHAR(255) NOT NULL,
                        reasons VARCHAR(255),
                        privateReason SMALLINT NOT NULL,
                        FKTimeSlotBase INTEGER,
                        CONSTRAINT FKTimeSlotBaseAbsence FOREIGN KEY(FKTimeSlotBase) REFERENCES TimeSlotBase (numTimeSlot),
                        FKTimeSlotPunctual INTEGER,
                        CONSTRAINT FKTimeSlotPunctualAbsence FOREIGN KEY(FKTimeSlotPunctual) REFERENCES TimeSlotPunctual (numTimeSlot),
                        FKnumInterpreter INTEGER,
                        CONSTRAINT FKnumInterpreterAbsence FOREIGN KEY(FKnumInterpreter) REFERENCES Interpreter (numInterpreter));

CREATE TABLE Coordinator (  numCoordinator INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            isAdmin SMALLINT NOT NULL,
                            FKnumInterpreter INTEGER,
                            CONSTRAINT FKnumInterpreterCoordinator FOREIGN KEY(FKnumInterpreter) REFERENCES Interpreter (numInterpreter));

CREATE TABLE AcademicSkill (    numAcademicSkill INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                designation VARCHAR(255) NOT NULL);

CREATE TABLE AcademicSkillInterpreter ( numAcademicSkill INTEGER,
                                        numInterpreter INTEGER,
                                        CONSTRAINT PKAcademicSkillInterpreter PRIMARY KEY (numAcademicSkill, numInterpreter),
                                        CONSTRAINT FKnumAcademicSkillInterpreter FOREIGN KEY(numAcademicSkill) REFERENCES AcademicSkill (numAcademicSkill),
                                        CONSTRAINT FKnumInterpreterAcademicSkillInterpreter FOREIGN KEY(numInterpreter) REFERENCES Interpreter (numInterpreter));

CREATE TABLE Establishment( numEstablishment INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            FKAddress INTEGER NOT NULL UNIQUE,
                            CONSTRAINT FKAddressEstablishment FOREIGN KEY(FKAddress) REFERENCES Address (numAddress),
                            name VARCHAR(255),
                            phoneNumber VARCHAR(255),
                            educationLevel VARCHAR(255) NOT NULL);

CREATE TABLE Beneficiary(   numBeneficiary INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            login VARCHAR(255) NOT NULL,
                            password VARCHAR(255) NOT NULL,
                            firstName VARCHAR(255) NOT NULL,
                            lastName VARCHAR(255) NOT NULL,
                            phoneNumber VARCHAR(255) NOT NULL,
                            emailAddress VARCHAR(255) NOT NULL,
                            hourQuota INTEGER NOT NULL,
                            educationLevel INTEGER NOT NULL,
                            communicationLanguage VARCHAR(255),
                            FKnumInterpreter INTEGER,
                            CONSTRAINT FKnumInterpreterBeneficiary FOREIGN KEY (FKnumInterpreter) REFERENCES Interpreter (numInterpreter),
                            FKAddress INTEGER NOT NULL,
                            CONSTRAINT FKAddressBeneficiary FOREIGN KEY(FKAddress) REFERENCES Address (numAddress));


CREATE TABLE Appointment(   numAppointment INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            description VARCHAR(255),
                            status VARCHAR(255) NOT NULL,
                            local VARCHAR(255), -- list of locals Ex : M5,M6
