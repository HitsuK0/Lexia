                                        CONSTRAINT FKnumProfessionalSkillRequiredProfessionalSkill FOREIGN KEY (numProfessionalSkill) REFERENCES ProfessionalSkill(numProfessionalSkill));

CREATE TABLE ProfessionalSkillInterpreter(  numProfessionalSkill INTEGER,
                                            numInterpreter INTEGER,
                                            PRIMARY KEY (numProfessionalSkill, numInterpreter),
                                            CONSTRAINT FKnumProfessionalSkillProfessionalSkillInterpreter FOREIGN KEY (numProfessionalSkill) REFERENCES ProfessionalSkill(numProfessionalSkill),
