    /**
     * Searches for an Absence by its numAbsence.
     * The TimeSlotPunctual is loaded via DAOTimeSlotPunctual
     *
     * @param objectToSearchInDB the numAbsence to search for
     * @return The Absence if found, null otherwise
     * @throws SQLException In case of any SQL problems encountered with this method
     */
    public Absence find(int objectToSearchInDB) throws SQLException {
        Absence absence = null;
        PreparedStatement preparedStatement = null;
        ResultSet resultSet = null;

        String query = "SELECT status, reasons, privateReason, FKTimeSlotBase, FKTimeSlotPunctual " +
                "FROM Absence " +
                "WHERE numAbsence = ?";

        try {
            preparedStatement = connect.prepareStatement(query);
            preparedStatement.setInt(1, objectToSearchInDB);

            resultSet = preparedStatement.executeQuery();

            if (resultSet.next()) {
                TimeSlot timeSlot = null;

                if (resultSet.getObject("FKTimeSlotBase") != null) {
                    DAOTimeSlotBase daoTimeSlotBase = new DAOTimeSlotBase();
                    timeSlot = daoTimeSlotBase.find(resultSet.getInt("FKTimeSlotBase"));
                } else {
                    DAOTimeSlotPunctual daoTimeSlotPunctual = new DAOTimeSlotPunctual();
                    timeSlot = daoTimeSlotPunctual.find(resultSet.getInt("FKTimeSlotPunctual"));
                }

                absence = new Absence(objectToSearchInDB, resultSet.getString("status"), timeSlot,
                        resultSet.getString("reasons"), resultSet.getBoolean("privateReason"));
            }
        } catch (BadStatusException e) {
            e.printStackTrace();
        } finally {
            closeStatementAndResultSet(preparedStatement, resultSet);
        }
        return absence;
    }

    /**
     * Creates a list containing all the Absence in the Absence table
     * For each Absence, the TimeSlotPunctual is loaded via DAOTimeSlotPunctual
     *
     * @return A list containing all the Absence, or an empty list if the table is empty
     * @throws SQLException In case of any SQL problems encountered with this method
     */
    public List<Absence> findAll() throws SQLException {
        List<Absence> absenceList = new ArrayList<Absence>();
        PreparedStatement preparedStatement = null;
        ResultSet resultSet = null;

        String query = "SELECT numAbsence, status, reasons, privateReason, FKTimeSlotBase, FKTimeSlotPunctual " +
                "FROM Absence";

        try {
            preparedStatement = connect.prepareStatement(query);
            resultSet = preparedStatement.executeQuery();

            DAOTimeSlotPunctual daoTimeSlotPunctual = new DAOTimeSlotPunctual();
            DAOTimeSlotBase daoTimeSlotBase = new DAOTimeSlotBase();
            TimeSlot timeSlot = null;

            while (resultSet.next()) {
                if (resultSet.getObject("FKTimeSlotBase") != null) {
                    timeSlot = daoTimeSlotBase.find(resultSet.getInt("FKTimeSlotBase"));
                } else {
                    timeSlot = daoTimeSlotPunctual.find(resultSet.getInt("FKTimeSlotPunctual"));
                }

                Absence absence = new Absence(resultSet.getInt("numAbsence"), resultSet.getString("status"),
                        timeSlot, resultSet.getString("reasons"), resultSet.getBoolean("privateReason"));

                absenceList.add(absence);
            }
        } catch (BadStatusException e) {
            e.printStackTrace();
        } finally {
            closeStatementAndResultSet(preparedStatement, resultSet);
        }
        return absenceList;
    }

    /**
     * Adds the Absence passed as a parameter to the Absence table without any associated User
     * The numAbsence is auto-generated by Oracle
     * Precondition: the Absence passed as a parameter cannot be null
     * Precondition: the TimeSlot of the Absence must already exist in the database
     *
     * @param objectToInsertInDB the Absence to be inserted into the table
     * @return true if the Absence is successfully inserted, false otherwise
     * @throws SQLException In case of any SQL problems encountered with this method
     */
    public boolean create(Absence objectToInsertInDB) throws SQLException {
        boolean isCreated = false;
        OraclePreparedStatement preparedStatement = null;
        ResultSet generateID = null;

        String query = "INSERT INTO Absence(status, reasons, privateReason, FKTimeSlotBase, FKTimeSlotPunctual, FKnumInterpreter) " +
                "VALUES (?, ?, ?, ?, ?, ?) " +
                "RETURNING numAbsence  INTO ?";

        try {
            preparedStatement = (OraclePreparedStatement) connect.prepareStatement(query);

            preparedStatement.setString(1, objectToInsertInDB.getStatus());
            preparedStatement.setString(2, objectToInsertInDB.getReason());
            preparedStatement.setBoolean(3, objectToInsertInDB.isPrivateReason());

            if (objectToInsertInDB.getTimeSlot() instanceof TimeSlotBase) {
                preparedStatement.setInt(4, objectToInsertInDB.getTimeSlot().getNumTimeSlot());
                preparedStatement.setNull(5, java.sql.Types.INTEGER);
            } else {
                preparedStatement.setNull(4, java.sql.Types.INTEGER);
                preparedStatement.setInt(5, objectToInsertInDB.getTimeSlot().getNumTimeSlot());
            }

            preparedStatement.setNull(6, java.sql.Types.INTEGER);

            preparedStatement.registerReturnParameter(7, OracleTypes.INTEGER);

            if (preparedStatement.executeUpdate() > 0) {
                generateID = preparedStatement.getReturnResultSet();
                if (!generateID.next()) {
                    throw new SQLException("[DAOAbsence] Impossible de récupérer le ID généré");
                }

                int numAbsenceGenerated = generateID.getInt(1);
                objectToInsertInDB.setNumAbsence(numAbsenceGenerated);

                isCreated = true;
            }
        } finally {
            closeStatementAndResultSet(preparedStatement, generateID);
        }
        return isCreated;
    }

