-- Trigger
-- ────────────────────────────────────────────────────────────
-- Hash the password of an Interpreter on INSERT or UPDATE.
-- The hash is only recomputed on UPDATE if the password field
-- has actually changed, to avoid unnecessary rehashing.
-- Algorithm: SHA256 via Oracle STANDARD_HASH.
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_hash_password_interprete
BEFORE INSERT OR UPDATE ON Interpreter
                            FOR EACH ROW
DECLARE
hash_pwd VARCHAR2(255);
BEGIN
            IF INSERTING OR (UPDATING AND :NEW.password != :OLD.password) THEN
SELECT STANDARD_HASH(:NEW.password, 'SHA256')
INTO hash_pwd
FROM dual;
:NEW.password := hash_pwd;
END IF;
END;
/

