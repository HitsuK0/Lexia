

CREATE TABLE Address (  numAddress INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                        postalCode INTEGER NOT NULL,
                        postalBox VARCHAR2(255) NOT NULL,
                        locality VARCHAR2(255) NOT NULL,
                        hamlet VARCHAR2(255));

CREATE TABLE TimeSlotBase ( numTimeSlot INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            startTime DATE NOT NULL,
                            duration DATE NOT NULL,
                            dayNumber INTEGER NOT NULL);

CREATE TABLE TimeSlotPunctual ( numTimeSlot INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                                startTime DATE NOT NULL,
                                duration DATE NOT NULL,
                                startDate DATE NOT NULL,
                                endDate DATE NOT NULL);

CREATE TABLE Interpreter (  numInterpreter INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                            login VARCHAR2(255) NOT NULL,
                            password VARCHAR2(255) NOT NULL,
                            lastName VARCHAR2(255) NOT NULL,
                            firstName VARCHAR2(255) NOT NULL,
                            emailAddress VARCHAR2(255) NOT NULL,
                            phoneNumber VARCHAR2(255) NOT NULL,
                            weeklyWorkHours INTEGER NOT NULL,
                            FKAddress INTEGER NOT NULL,
                            CONSTRAINT FKAddressInterpreter FOREIGN KEY(FKAddress) REFERENCES Address (numAddress));

CREATE TABLE Absence (  numAbsence INTEGER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
                        status VARCHAR2(255) NOT NULL,
                        reasons VARCHAR2(255),
                        privateReason NUMBER(1) NOT NULL,
                        FKTimeSlotBase INTEGER,
                        CONSTRAINT FKTimeSlotBaseAbsence FOREIGN KEY(FKTimeSlotBase) REFERENCES TimeSlotBase (numTimeSlot),
                        FKTimeSlotPunctual INTEGER,
                        CONSTRAINT FKTimeSlotPunctualAbsence FOREIGN KEY(FKTimeSlotPunctual) REFERENCES TimeSlotPunctual (numTimeSlot),
                        FKnumInterpreter INTEGER,
                        CONSTRAINT FKnumInterpreterAbsence FOREIGN KEY(FKnumInterpreter) REFERENCES Interpreter (numInterpreter));

