-- ────────────────────────────────────────────────────────────
-- Shared sequence used to generate unique login numbers
-- for Interpreters, Coordinators and Beneficiaries.
-- Format: I0001, C0001, B0001 (prefix + 4-digit padded number).
-- ────────────────────────────────────────────────────────────
CREATE SEQUENCE seq_userlexia_login
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

-- ────────────────────────────────────────────────────────────
-- Auto-generate the login of an Interpreter on INSERT
-- if no login was provided.
-- Format: 'I' followed by a 4-digit zero-padded sequence number.
-- Example: I0001, I0002, I0042
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_generate_login_interpreter
BEFORE INSERT ON Interpreter
FOR EACH ROW
DECLARE
v_seq_num NUMBER(10);
BEGIN
    IF :NEW.login IS NULL THEN
        v_seq_num := SEQ_USERLEXIA_LOGIN.NEXTVAL;

            :NEW.login := 'I' || LPAD(v_seq_num, 4, '0');

END IF;
END;
/

-- ────────────────────────────────────────────────────────────
-- Auto-generate the login of a Coordinator on INSERT.
-- Updates the login of the linked Interpreter row to use
-- the 'C' prefix instead of 'I', since a Coordinator
-- is stored as an Interpreter with an elevated role.
-- Format: 'C' followed by a 4-digit zero-padded sequence number.
-- Example: C0003, C0007
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_generate_login_coordinator
BEFORE INSERT ON Coordinator
FOR EACH ROW
BEGIN

UPDATE Interpreter
SET login = 'C' || LPAD(SEQ_USERLEXIA_LOGIN.NEXTVAL, 4, '0')
WHERE numInterpreter = :NEW.FKnumInterpreter;

END;
/

-- ────────────────────────────────────────────────────────────
-- Auto-generate the login of a Beneficiary on INSERT
-- if no login was provided.
-- Format: 'B' followed by a 4-digit zero-padded sequence number.
-- Example: B0001, B0002, B0099
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_generate_login_beneficiairy
BEFORE INSERT ON Beneficiary
FOR EACH ROW
DECLARE
v_seq_num NUMBER(10);
BEGIN
    IF :NEW.login IS NULL THEN
        v_seq_num := SEQ_USERLEXIA_LOGIN.NEXTVAL;
            :NEW.login := 'B' || LPAD(v_seq_num, 4, '0');

END IF;
END;
/


-- ────────────────────────────────────────────────────────────
-- Delete an Appointment
-- Dependencies: RequiredAcademicSkill, RequiredProfessionalSkill, RDVInterpreter
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_delete_appointment
BEFORE DELETE ON Appointment
FOR EACH ROW
BEGIN
DELETE FROM RequiredAcademicSkill     WHERE numAppointment = :OLD.numAppointment;
DELETE FROM RequiredProfessionalSkill WHERE numAppointment = :OLD.numAppointment;
DELETE FROM RDVInterpreter            WHERE numAppointment = :OLD.numAppointment;
END;
/


-- ────────────────────────────────────────────────────────────
-- Delete a Beneficiary
-- Dependencies: Appointment
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_delete_beneficiary
BEFORE DELETE ON Beneficiary
FOR EACH ROW
BEGIN
DELETE FROM Appointment WHERE FKnumBeneficiary = :OLD.numBeneficiary;
END;
/


-- ────────────────────────────────────────────────────────────
-- Delete an Interpreter
-- Dependencies: Absence, Coordinator, RDVInterpreter,
--               AcademicSkillInterpreter, ProfessionalSkillInterpreter,
--               Beneficiary.FKnumInterpreter
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE TRIGGER trg_delete_interpreter
BEFORE DELETE ON Interpreter
FOR EACH ROW
BEGIN
DELETE FROM Absence                  WHERE FKnumInterpreter = :OLD.numInterpreter;

DELETE FROM Coordinator              WHERE FKnumInterpreter = :OLD.numInterpreter;

DELETE FROM RDVInterpreter           WHERE numInterpreter   = :OLD.numInterpreter;

DELETE FROM AcademicSkillInterpreter     WHERE numInterpreter = :OLD.numInterpreter;

DELETE FROM ProfessionalSkillInterpreter WHERE numInterpreter = :OLD.numInterpreter;

UPDATE Beneficiary SET FKnumInterpreter = NULL WHERE FKnumInterpreter = :OLD.numInterpreter;
END;
/


